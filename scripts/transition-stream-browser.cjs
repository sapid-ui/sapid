const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium, writeReport } = require('./showcase-browser-env.cjs');
(async () => {
  assert(process.env.SAPID_PRESENCE_FIXTURE, 'Pass a fixture generated by the current Glory workspace');
  const html = fs.readFileSync(process.env.SAPID_PRESENCE_FIXTURE, 'utf8');
  const script = fs.readFileSync(path.resolve(__dirname, '../../glory/crates/web/src/stream.js'), 'utf8');
  const browser = await chromium.launch(); const page = await browser.newPage();
  const report = { browser: browser.version(), passed: false, errors: [] };
  page.on('pageerror', e => report.errors.push(e.message));
  try {
    await page.route('http://presence.test/**', route => route.fulfill({ contentType: route.request().url().endsWith('.js') ? 'text/javascript' : 'text/html', body: route.request().url().endsWith('.js') ? script : html }));
    await page.addInitScript(() => {
      new MutationObserver(() => { if (!window.originalPresenceInput) window.originalPresenceInput = document.querySelector('input'); }).observe(document, { childList: true, subtree: true });
    });
    await page.goto('http://presence.test/');
    await page.waitForFunction(() => document.getElementById('presence-root')?.getAttribute('data-gly-stream-state') === 'ready');
    const input = page.getByRole('textbox', { name: 'Retained stream draft', exact: true });
    await input.waitFor(); assert.equal(await input.inputValue(), 'draft'); assert(await input.evaluate(e => e === window.originalPresenceInput));
    assert.equal(await page.locator('[data-gly-presence]').getAttribute('data-gly-presence'), 'open');
    assert.equal(await page.locator('[data-gly-presence]').getAttribute('data-gly-presence-revision'), '1');
    assert.deepEqual(report.errors, []); report.passed = true;
  } finally { writeReport('transition-stream.json', report); await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
